create table if not exists public.store_categories (
 id bigint generated by default as identity primary key,
 name text not null unique, emoji text not null default '📦',
 active boolean not null default true, created_at timestamptz not null default now()
);
alter table public.store_categories enable row level security;
drop policy if exists "Public can read active store categories" on public.store_categories;
create policy "Public can read active store categories" on public.store_categories for select to anon, authenticated using (active=true);
drop policy if exists "Authenticated users manage store categories" on public.store_categories;
create policy "Authenticated users manage store categories" on public.store_categories for all to authenticated using (true) with check (true);
create table if not exists public.store_reviews (
 id bigint generated by default as identity primary key, product_id text not null,
 customer_name text not null, rating integer not null check (rating between 1 and 5),
 comment text not null, owner_reply text, approved boolean not null default false,
 created_at timestamptz not null default now()
);
alter table public.store_reviews enable row level security;
drop policy if exists "Public can read approved reviews" on public.store_reviews;
create policy "Public can read approved reviews" on public.store_reviews for select to anon, authenticated using (approved=true);
drop policy if exists "Customers submit reviews" on public.store_reviews;
create policy "Customers submit reviews" on public.store_reviews for insert to anon, authenticated with check (rating between 1 and 5 and length(trim(customer_name))>0 and length(trim(comment))>0);
drop policy if exists "Authenticated owners manage reviews" on public.store_reviews;
create policy "Authenticated owners manage reviews" on public.store_reviews for update to authenticated using (true) with check (true);

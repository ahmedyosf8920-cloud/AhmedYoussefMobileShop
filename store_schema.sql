-- مساحة صور عامة للقراءة، والرفع مقتصر على المستخدم المسجل داخل مجلد رقمه الشخصي.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('store-product-images', 'store-product-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "Public can view store product images" on storage.objects;
create policy "Public can view store product images" on storage.objects for select to anon, authenticated using (bucket_id = 'store-product-images');
drop policy if exists "Owners upload own store product images" on storage.objects;
create policy "Owners upload own store product images" on storage.objects for insert to authenticated with check (bucket_id = 'store-product-images' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Owners update own store product images" on storage.objects;
create policy "Owners update own store product images" on storage.objects for update to authenticated using (bucket_id = 'store-product-images' and (storage.foldername(name))[1] = auth.uid()::text) with check (bucket_id = 'store-product-images' and (storage.foldername(name))[1] = auth.uid()::text);


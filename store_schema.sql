-- شغّل هذا الملف مرة واحدة في Supabase > SQL Editor > New query.
-- ينشئ جدولًا عامًا لمنتجات المتجر فقط؛ لا يفتح بيانات المبيعات أو العملاء أو التكلفة.
create table if not exists public.store_products (
  owner_id uuid not null references auth.users(id) on delete cascade,
  product_id text not null,
  name text not null,
  sku text not null default '',
  category text not null default 'أخرى',
  description text not null default '',
  price numeric not null default 0,
  original_price numeric not null default 0,
  discount_type text not null default 'بدون خصم',
  discount_value numeric not null default 0,
  image_url text not null default '',
  quantity numeric not null default 0,
  emoji text not null default '📦',
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (owner_id, product_id)
);

alter table public.store_products enable row level security;

grant select on public.store_products to anon, authenticated;
grant insert, update, delete on public.store_products to authenticated;

drop policy if exists "Public can view active store products" on public.store_products;
create policy "Public can view active store products"
on public.store_products for select
to anon, authenticated
using (active = true);

drop policy if exists "Owner can manage own store products" on public.store_products;
create policy "Owner can manage own store products"
on public.store_products for all
to authenticated
using (owner_id = auth.uid())
with check (owner_id = auth.uid());

